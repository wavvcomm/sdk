#!/usr/bin/env node
/**
 * Build, verify and publish `@wavv/sdk`.
 *
 *   node scripts/release.mjs build               clean dist, write src/version.ts, check-actions, compile, write REFERENCE.md
 *   node scripts/release.mjs verify              build, then inspect what `npm pack` would ship
 *   node scripts/release.mjs publish --dry-run   every publish check, then `npm publish --dry-run`
 *   node scripts/release.mjs publish             the real thing: publish to npm and tag `sdk-v<version>`
 *
 * `verify` also runs as `prepublishOnly`, so a bare `npm publish` cannot ship a stale or unchecked build.
 * See `PUBLISHING.md` for the order of operations — the core deploy comes first.
 *
 * Dependency-free itself, because `pnpm install` is not always healthy in this repository. The one exception
 * is `REFERENCE.md`, rendered by `api-docs/` (which needs its `yaml`) when that folder is beside this one.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(resolve(SDK, 'package.json'), 'utf8'));
const TAG = `sdk-v${pkg.version}`;

/** What a published tarball may contain, and what it must. Anything else is a leak. */
const ALLOWED = /^(package\.json|README\.md|REFERENCE\.md|LICENSE|dist\/[a-z]+\.(js|d\.ts))$/;
const REQUIRED = ['package.json', 'README.md', 'REFERENCE.md', 'LICENSE', 'dist/index.js', 'dist/index.d.ts'];

const step = (message) => process.stdout.write(`\n▸ ${message}\n`);
const fail = (message) => {
	process.stderr.write(`\n✗ ${message}\n`);
	process.exit(1);
};
const run = (cmd, args, options = {}) => execFileSync(cmd, args, { cwd: SDK, stdio: 'inherit', ...options });
const read = (cmd, args) => execFileSync(cmd, args, { cwd: SDK, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();

/** The sdk's own TypeScript when installed, otherwise the copy front-end already has. */
const findTsc = () => {
	const candidates = ['node_modules/.bin/tsc', '../node_modules/.bin/tsc', '../front-end/node_modules/.bin/tsc'];
	const found = candidates.map((path) => resolve(SDK, path)).find((path) => existsSync(path));
	return found ?? fail(`No tsc found. Looked in:\n  ${candidates.join('\n  ')}`);
};

/**
 * `src/version.ts`, generated from `package.json` so a release bumps one file. Committed all the same, so
 * the GitHub mirror and type-checks always have it; `check-actions` then confirms the two agree.
 */
const versionSource = (version) => `/**
 * Stamped onto every dispatched action so core can log which module and version a call came from
 * (\`logFunctionCall\` in \`storm-js/src/dispatch.js\`) and decide whether to validate its payload.
 *
 * GENERATED by \`scripts/release.mjs\` from \`package.json\` on every build — do not edit by hand; bump the
 * version in \`package.json\` instead. \`scripts/check-actions.mjs\` asserts they match.
 */
export const MODULE = 'sdk';
export const VERSION = '${version}';
`;

const writeVersion = () => {
	step('Writing src/version.ts from package.json');
	const path = resolve(SDK, 'src/version.ts');
	const next = versionSource(pkg.version);
	const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
	if (current === next) {
		process.stdout.write(`  unchanged (${pkg.version})\n`);
		return;
	}
	writeFileSync(path, next);
	process.stdout.write(`  updated to ${pkg.version}\n`);
};

/**
 * `REFERENCE.md`: the SDK docs as one Markdown file, shipped in the package so a coding assistant can
 * read them from `node_modules` — the hosted docs at sdk.wavv.com sit behind a login. Rendered by
 * `api-docs/` exactly as the hosted Markdown is (the SDK overlay over the public spec, plus `dist/*.d.ts`),
 * so it must run after compiling.
 *
 * Committed, like `src/version.ts`: the GitHub mirror that publishes carries only `sdk/` and
 * `common/src/types.js`, not `api-docs/`, so there it ships the committed copy instead of rendering one.
 */
const writeReference = async () => {
	step('Writing REFERENCE.md from api-docs and dist/');
	const path = resolve(SDK, 'REFERENCE.md');
	const apiDocs = resolve(SDK, '../api-docs/lib');
	const stamp = `${pkg.name}@${pkg.version}`;
	if (!existsSync(apiDocs)) {
		if (!existsSync(path)) fail('No api-docs/ beside sdk/ to render REFERENCE.md, and no committed copy to ship.');
		// The committed copy cannot be re-rendered here, but it must at least be the one rendered for this version.
		if (!readFileSync(path, 'utf8').split(/\s/).includes(stamp)) {
			fail(`REFERENCE.md was not rendered for ${stamp}. Run \`node scripts/release.mjs build\` in storm and commit REFERENCE.md.`);
		}
		process.stdout.write(`  no api-docs/ here; shipping the committed copy (${stamp})\n`);
		return;
	}
	const load = (name) => import(pathToFileURL(resolve(apiDocs, name)).href);
	let modules;
	try {
		modules = await Promise.all([load('spec.mjs'), load('sdk-model.mjs'), load('render-markdown.mjs')]);
	} catch (error) {
		fail(`Could not load api-docs to render REFERENCE.md (run \`pnpm install\` at the repo root):\n  ${error.message}`);
	}
	const [{ loadDoc }, { collectSdk }, { renderMarkdown }] = modules;

	const doc = await loadDoc({ scope: 'platform' });
	// Name the version so a reader can tell the reference matches the package it sits in.
	doc.info['x-wavv-meta'] = doc.info['x-wavv-meta'].map((meta) => (meta.value === pkg.name ? { ...meta, value: stamp } : meta));
	const next = renderMarkdown(doc, collectSdk(resolve(SDK, 'dist')));
	const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
	if (current === next) {
		process.stdout.write('  unchanged\n');
		return;
	}
	writeFileSync(path, next);
	process.stdout.write(`  updated (${(Buffer.byteLength(next) / 1024).toFixed(1)} kB) — commit it\n`);
};

const build = async () => {
	step('Cleaning dist/');
	rmSync(resolve(SDK, 'dist'), { recursive: true, force: true });

	writeVersion();

	step('Checking action names and version against core');
	run('node', ['scripts/check-actions.mjs']);

	step('Compiling');
	run(findTsc(), ['-p', 'tsconfig.build.json']);

	await writeReference();
};

const inspectPack = () => {
	step('Inspecting what npm would ship');
	// `--ignore-scripts` stops `npm pack` re-entering this script through lifecycle hooks.
	const raw = read('npm', ['pack', '--dry-run', '--json', '--ignore-scripts']);
	const packed = JSON.parse(raw);
	// npm ≤ 11 prints a one-element array; npm 12 prints an object keyed by package name.
	const { files, size, unpackedSize } = (Array.isArray(packed) ? packed[0] : (packed?.[pkg.name] ?? packed)) ?? {};
	if (!Array.isArray(files)) fail(`Could not read the file list from \`npm pack --json\`. It printed:\n  ${raw.slice(0, 300)}`);
	const paths = files.map((file) => file.path).sort();

	for (const path of paths) process.stdout.write(`  ${path}\n`);
	process.stdout.write(`  ${paths.length} files, ${(size / 1024).toFixed(1)} kB packed, ${(unpackedSize / 1024).toFixed(1)} kB unpacked\n`);

	const leaked = paths.filter((path) => !ALLOWED.test(path));
	const missing = REQUIRED.filter((path) => !paths.includes(path));
	if (leaked.length) fail(`The package would ship files it should not:\n  ${leaked.join('\n  ')}`);
	if (missing.length) fail(`The package is missing:\n  ${missing.join('\n  ')}`);
};

const verify = async () => {
	await build();
	inspectPack();
	process.stdout.write(`\n✓ ${pkg.name}@${pkg.version} is built and ships only what it should.\n`);
};

/** Ask a question and require the exact answer. Anything else aborts. */
const confirm = async (question, expected) => {
	const prompt = createInterface({ input: process.stdin, output: process.stdout });
	const answer = (await prompt.question(`\n${question} `)).trim();
	prompt.close();
	if (answer !== expected) fail('Aborted. Nothing was published.');
};

const publish = async ({ dryRun }) => {
	step('Checking npm login');
	try {
		process.stdout.write(`  logged in as ${read('npm', ['whoami', '--registry', pkg.publishConfig.registry])}\n`);
	} catch {
		const problem = 'Not logged in to npm. Run `npm login` and try again.';
		if (!dryRun) fail(problem);
		process.stdout.write(`  ! ${problem}\n`);
	}

	// Build first: it rewrites src/version.ts and REFERENCE.md, so the clean-tree check below must see what it wrote.
	await verify();

	step('Checking git');
	const branch = read('git', ['rev-parse', '--abbrev-ref', 'HEAD']);
	const dirty = read('git', ['status', '--porcelain', '--', '.']);
	const problems = [
		dirty && `sdk/ has uncommitted changes — publish only what is committed:\n${dirty}`,
		branch !== 'master' && `On ${branch}. Publish from master, after the core it needs is deployed.`,
		read('git', ['tag', '--list', TAG]) && `Tag ${TAG} already exists. Bump the version first.`,
	].filter(Boolean);
	// A dry run reports these and carries on, so the rest of the pipeline can be rehearsed from a branch.
	if (problems.length && !dryRun) fail(problems.join('\n'));
	for (const problem of problems) process.stdout.write(`  ! ${problem}\n`);
	if (!problems.length) process.stdout.write(`  ${branch}, sdk/ clean, ${TAG} is free\n`);

	step('Checking the version is unpublished');
	try {
		read('npm', ['view', `${pkg.name}@${pkg.version}`, 'version']);
		fail(`${pkg.name}@${pkg.version} is already on npm. Bump the version in package.json.`);
	} catch (error) {
		// `npm view` exits non-zero with E404 for an unpublished version or a package that does not exist yet.
		if (!String(error.stderr ?? error.message).includes('E404')) throw error;
	}
	process.stdout.write(`  ${pkg.version} is free\n`);

	if (dryRun) {
		step('npm publish --dry-run');
		run('npm', ['publish', '--dry-run', '--ignore-scripts']);
		process.stdout.write(`\n✓ Dry run complete. Nothing was published and no tag was created.\n`);
		return;
	}

	await confirm('Is every core change this release needs deployed to PRODUCTION? Type "deployed":', 'deployed');
	await confirm(`This publishes ${pkg.name}@${pkg.version} publicly and permanently. Type the version to continue:`, pkg.version);

	step('Publishing');
	// The build was verified above; skipping `prepublishOnly` avoids building it a second time.
	run('npm', ['publish', '--ignore-scripts']);

	step(`Tagging ${TAG}`);
	run('git', ['tag', '-a', TAG, '-m', `${pkg.name}@${pkg.version}`]);
	run('git', ['push', 'origin', TAG]);

	process.stdout.write(`\n✓ Published ${pkg.name}@${pkg.version} — https://www.npmjs.com/package/${pkg.name}\n`);
};

const [command, ...flags] = process.argv.slice(2);

if (command === 'build') await build();
else if (command === 'verify') await verify();
else if (command === 'publish') await publish({ dryRun: flags.includes('--dry-run') });
else fail('Usage: node scripts/release.mjs build | verify | publish [--dry-run]');
